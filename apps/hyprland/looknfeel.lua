-- Screen shader + the damage_tracking it needs, saved by shaders/crt-toggle.sh
-- (SUPER+ALT+C / SUPER+ALT+SHIFT+C). File holds "<path> <damage_tracking>".
do
	local state = (os.getenv("XDG_STATE_HOME") or (os.getenv("HOME") .. "/.local/state")) .. "/hypr/screen-shader"
	local sf = io.open(state, "r")
	local line = sf and sf:read("*l")
	if sf then
		sf:close()
	end
	local path, dt = (line or ""):match("^(%S+)%s+(%d)$")
	local exists = path and io.open(path, "r")
	if exists then
		exists:close()
		hl.config({ decoration = { screen_shader = path }, debug = { damage_tracking = tonumber(dt) } })
	end
end

-- Transparency and blur presets saved by opacity.sh (SUPER+ALT+O) and
-- blur.sh (SUPER+ALT+U), also picked in the customizer. Each state file holds
-- "<name> <values...>", so the preset tables live only in those scripts.
do
	local dir = (os.getenv("XDG_STATE_HOME") or (os.getenv("HOME") .. "/.local/state")) .. "/hypr/"
	local function values(name)
		local f = io.open(dir .. name, "r")
		local line = f and f:read("*l")
		if f then
			f:close()
		end
		local out = {}
		for n in (line or ""):gmatch("%s([%d.]+)") do
			out[#out + 1] = tonumber(n)
		end
		return out
	end

	local o = values("opacity")
	if #o == 2 then
		hl.config({ decoration = { active_opacity = o[1], inactive_opacity = o[2] } })
	end

	local b = values("blur")
	if #b == 4 then
		hl.config({ decoration = { blur = {
			enabled = b[1] > 0,
			size = math.max(1, b[1]),
			passes = b[2],
			vibrancy = b[3],
			noise = b[4],
		} } })
	end
end

